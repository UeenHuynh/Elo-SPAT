function outputs = run_integrated_layer_validation_20deg(outputDir, stopAfterZero, resumeZeroDir)
% run_integrated_layer_validation_20deg  Native MATLAB reduced layer audit.
%
% Rebuilds the 20-degree dij from the preserved Dense Arc artifact, validates
% native objective/gradient and a small final IPOPT solve, then tests nonzero
% scale-normalized lambdaEL values. Spot/ES/time penalties remain disabled.

narginchk(0, 3);
workspaceDir = fileparts(fileparts(mfilename('fullpath')));
add_module_paths(workspaceDir);
if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(workspaceDir, 'results', ...
        ['integrated_layer_validation_20deg_' datestr(now, 'yyyymmdd_HHMMSS')]);
end
if nargin < 2 || isempty(stopAfterZero)
    stopAfterZero = false;
end
if nargin < 3 || isempty(resumeZeroDir)
    resumeZeroDir = '';
end
if exist(outputDir, 'dir') == 7
    entries = dir(outputDir);
    entries = entries(~ismember({entries.name}, {'.', '..'}));
    if ~isempty(entries)
        error('run_integrated_layer_validation_20deg:nonemptyOutputDirectory', ...
            ['Output directory is not empty. Use a job-specific directory ' ...
             'to prevent stale validation files from being reused: %s'], outputDir);
    end
else
    mkdir(outputDir);
end

artifactFile = fullfile(workspaceDir, 'results', ...
    'task25_27_pipeline_20deg.mat');
source = load(artifactFile, 'cfg', 'machine', 'denseResult', ...
    'dij', 'pln', 'stf', 'map', 'groups', 'cpGroups');
required = {'cfg','machine','denseResult','dij','pln','stf','map','groups'};
for iRequired = 1:numel(required)
    if ~isfield(source, required{iRequired})
        error('run_integrated_layer_validation_20deg:artifactMissingField', ...
            'Dense Arc artifact is missing %s.', required{iRequired});
    end
end
patient = load(source.cfg.patientFile, 'ct', 'cst');
cfg = merge_structs_local(default_config(), source.cfg);
cfg.mode = 'integrated';
cfg.robust.enabled = false;
cfg.integrated.componentStage = 'layer';
cfg.lambdaB = 0; cfg.lambdaS = 0; cfg.lambdaES = 0; cfg.lambdaT = 0;
cfg.integrated.constraintPenalty = 1e3;
cfg.integrated.maxIterations = 80;
cfg.integrated.relativeStepTolerance = 1e-5;
cfg.integrated.relativeObjectiveTolerance = 1e-6;
cfg.integrated.verbose = true;
cfg.integrated.runGradientCheck = true;
cfg.integrated.minimumValidationLayersPerCP = 10;
cfg.captureConsoleOutput = false;
machine = source.machine;

fprintf('Loading preserved 20-degree dij and mapping from Dense Arc artifact...\n');
pln = source.pln;
stf = source.stf;
dij = source.dij;
denseW = reshape(double(source.denseResult.w), [], 1);
if double(dij.totalNumOfBixels) ~= numel(denseW)
    error('run_integrated_layer_validation_20deg:geometryMismatch', ...
        'Rebuilt dij has %d spots; artifact has %d.', ...
        double(dij.totalNumOfBixels), numel(denseW));
end
map = source.map;
groups = source.groups;
if isfield(source, 'cpGroups') && ~isempty(source.cpGroups)
    cpGroups = source.cpGroups;
else
    [~, cpGroups] = build_group_index(map);
end
D = nominal_matrix(dij);
denseDoseDetail = dose_metrics(D, denseW, patient, cfg);
denseDose = denseDoseDetail.summary;
denseDelivery = compute_delivery_metrics(denseW, map, groups, cfg, machine);

% Numerical control: lambdaEL=0 is used only to validate native callbacks,
% mapping and a small locked-support IPOPT solve. It is never labelled sparse.
spotsPerControlPoint = 1200;
if isempty(resumeZeroDir)
    cfgZero = cfg;
    cfgZero.lambdaEL = 0;
    fprintf('\n=== Reduced numerical baseline (lambdaEL=0) ===\n');
    zero = run_integrated_reduced_validation(dij, patient.cst, pln, ...
        denseW, map, cfgZero, machine, spotsPerControlPoint, true);
    baselineW = zero.final.w;
    baselineDoseDetail = dose_metrics(D, baselineW, patient, cfg);
    baselineDose = baselineDoseDetail.summary;
    baselineDelivery = compute_delivery_metrics( ...
        baselineW, map, groups, cfg, machine);
    ipoptMetrics = compute_solver_metrics( ...
        zero.final.resultGUI, struct(), zero.final.optimizer);
    representativenessPass = quality_pass_detail( ...
        baselineDoseDetail, denseDoseDetail, cfg.evaluation.ctvD95TolerancePercent);
else
    checkpointFile = fullfile(resumeZeroDir, 'zero_lambda_checkpoint.mat');
    if exist(checkpointFile, 'file') ~= 2
        error('run_integrated_layer_validation_20deg:missingResumeCheckpoint', ...
            'Zero-lambda resume checkpoint does not exist: %s', checkpointFile);
    end
    fprintf('\n=== Resuming validated zero-lambda checkpoint from %s ===\n', ...
        checkpointFile);
    resumed = load(checkpointFile, 'zero', 'baselineDoseDetail', ...
        'baselineDose', 'baselineDelivery', 'ipoptMetrics', ...
        'representativenessPass');
    requiredResume = {'zero','baselineDoseDetail','baselineDose', ...
        'baselineDelivery','ipoptMetrics','representativenessPass'};
    for iResume = 1:numel(requiredResume)
        if ~isfield(resumed, requiredResume{iResume})
            error('run_integrated_layer_validation_20deg:invalidResumeCheckpoint', ...
                'Resume checkpoint is missing %s.', requiredResume{iResume});
        end
    end
    zero = resumed.zero;
    baselineDoseDetail = resumed.baselineDoseDetail;
    baselineDose = resumed.baselineDose;
    baselineDelivery = resumed.baselineDelivery;
    ipoptMetrics = resumed.ipoptMetrics;
    representativenessPass = resumed.representativenessPass;
end
assert(zero.doseEquivalenceRelativeError < 1e-12, ...
    'Reduced/full dose multiplication is not equivalent.');
assert(zero.gradient.maximumRelativeError < 5e-4, ...
    'Native matRad objective gradient failed reduced finite differences.');
assert(~isempty(zero.final), 'Small final IPOPT test did not run.');
assert(~any(abs(zero.final.w(~zero.supportFull)) > 1e-10), ...
    'Small final IPOPT violated fixed support.');
layerSelectionTable = struct2table(zero.selectionDiagnostics);
writetable(layerSelectionTable, fullfile(outputDir, ...
    'reduced_layer_diversity_by_cp.csv'));
fprintf('Reduced layer diversity per CP: min=%d, median=%.1f, max=%d.\n', ...
    zero.minimumSelectedLayersPerCP, zero.medianSelectedLayersPerCP, ...
    zero.maximumSelectedLayersPerCP);

zeroStructureTable = build_zero_structure_comparison( ...
    denseDoseDetail, baselineDoseDetail, cfg.evaluation.ctvD95TolerancePercent);
writetable(zeroStructureTable, fullfile(outputDir, ...
    'zero_lambda_dense_dose_comparison.csv'));
zeroSummary = build_zero_summary(zero, denseDose, denseDelivery, ...
    baselineDose, baselineDelivery, ipoptMetrics, representativenessPass);
writetable(struct2table(zeroSummary), fullfile(outputDir, ...
    'zero_lambda_summary.csv'));
writetable(trajectory_table(zero), fullfile(outputDir, ...
    'zero_lambda_objective_trajectory.csv'));
writetable(layer_group_table(zero), fullfile(outputDir, ...
    'zero_lambda_layer_groups.csv'));
save(fullfile(outputDir, 'zero_lambda_checkpoint.mat'), ...
    'zero', 'denseDoseDetail', 'baselineDoseDetail', 'denseDose', ...
    'baselineDose', 'denseDelivery', 'baselineDelivery', 'ipoptMetrics', ...
    'representativenessPass', 'zeroStructureTable', 'zeroSummary', ...
    'artifactFile', 'cfg', '-v7.3');
fprintf(['Zero-lambda Dense representativeness: %s. This gate is reported ' ...
    'separately and does not block numerical lambdaEL tests.\n'], ...
    pass_fail(representativenessPass));
if stopAfterZero
    fprintf(['ZERO-LAMBDA REPRODUCTION COMPLETE. No nonzero lambdaEL ' ...
        'tests were requested.\n']);
    outputs = struct('zeroLambdaReproductionComplete', true, ...
        'representativenessPassed', representativenessPass, ...
        'fullBenchmarkReady', false, 'outputDir', outputDir, ...
        'zeroSummary', zeroSummary);
    return;
end

scale = zero.initialParts.dose / max(zero.initialParts.layerL21half, eps);
alphaGrid = [1e-4; 3e-4; 1e-3; 3e-3; 1e-2; 3e-2; 1e-1; 3e-1; 1];
records = repmat(empty_record(), numel(alphaGrid), 1);
runs = cell(numel(alphaGrid), 1);
fprintf('\nLayer penalty scale Fdose/R_EL = %.8g\n', scale);
for i = 1:numel(alphaGrid)
    cfgTrial = cfg;
    cfgTrial.lambdaEL = alphaGrid(i) * scale;
    cfgTrial.integrated.runGradientCheck = false;
    fprintf('\n=== Reduced layer test alpha=%g, lambdaEL=%.8g ===\n', ...
        alphaGrid(i), cfgTrial.lambdaEL);
    checkpointFile = fullfile(outputDir, sprintf( ...
        'lambda_alpha_%s_checkpoint.mat', alpha_file_token(alphaGrid(i))));
    try
        trial = run_integrated_reduced_validation(dij, patient.cst, pln, ...
            denseW, map, cfgTrial, machine, spotsPerControlPoint, false);
        runs{i} = trial;
        metrics = summarize_plan(trial.wOptimizerFull, D, patient, map, ...
            groups, cfgTrial, machine);
        records(i) = make_record(alphaGrid(i), cfgTrial.lambdaEL, trial, ...
            metrics, baselineDose, zero.exactLayerStats);
        trajectory = trajectory_table(trial);
        writetable(trajectory, fullfile(outputDir, ...
            sprintf('lambda_alpha_%s_objective_trajectory.csv', ...
            alpha_file_token(alphaGrid(i)))));
        layerGroupTable = layer_group_table(trial);
        writetable(layerGroupTable, fullfile(outputDir, ...
            sprintf('lambda_alpha_%s_layer_groups.csv', ...
            alpha_file_token(alphaGrid(i)))));
        record = records(i); %#ok<NASGU>
        save(checkpointFile, 'trial', 'metrics', 'record', 'cfgTrial', ...
            'trajectory', 'layerGroupTable', '-v7.3');
    catch trialError
        records(i) = failed_record(alphaGrid(i), cfgTrial.lambdaEL, trialError);
        errorInfo = struct('errorIdentifier', trialError.identifier, ...
            'errorMessage', trialError.message);
        runs{i} = errorInfo;
        record = records(i); %#ok<NASGU>
        save(checkpointFile, 'record', 'cfgTrial', 'errorInfo', '-v7.3');
        warning('run_integrated_layer_validation_20deg:lambdaTrialFailed', ...
            'alpha=%g failed (%s): %s. Continuing sweep.', ...
            alphaGrid(i), trialError.identifier, trialError.message);
    end
    writetable(struct2table(records(1:i), 'AsArray', true), ...
        fullfile(outputDir, 'lambda_sweep.csv'));
end

recordTable = struct2table(records);
eligible = [records.exactLayerReduction] > 0 & ...
    [records.objectiveDescentPass] & [records.constraintPass] & ...
    [records.supportEmbeddingPreserved] & ...
    ~strcmp({records.status}, 'line_search_failed');
if ~any(eligible)
    save_outputs(false, NaN, zero, runs, recordTable, artifactFile, ...
        cfg, baselineDose, baselineDelivery, ipoptMetrics, outputDir);
    error('run_integrated_layer_validation_20deg:noPassingLambda', ...
        ['No nonzero lambdaEL produced exact layer elimination with objective ' ...
         'descent, feasibility, and consistent support extraction.']);
end
eligibleIx = find(eligible);
[~, bestLocal] = max([records(eligibleIx).layerReduction]);
selectedIx = eligibleIx(bestLocal);
selectedAlpha = alphaGrid(selectedIx);
selectedLambda = records(selectedIx).lambdaEL;

% Repeat only the selected nonzero lambda with the small final IPOPT test.
cfgSelected = cfg;
cfgSelected.lambdaEL = selectedLambda;
cfgSelected.integrated.runGradientCheck = false;
fprintf('\n=== Selected reduced final IPOPT: alpha=%g, lambdaEL=%.8g ===\n', ...
    selectedAlpha, selectedLambda);
selected = run_integrated_reduced_validation(dij, patient.cst, pln, ...
    denseW, map, cfgSelected, machine, spotsPerControlPoint, true);
save(fullfile(outputDir, 'selected_final_ipopt_raw_checkpoint.mat'), ...
    'selected', 'cfgSelected', 'selectedAlpha', 'selectedLambda', '-v7.3');
selectedMetrics = summarize_plan(selected.final.w, D, patient, map, ...
    groups, cfgSelected, machine);
selectedDoseDetail = dose_metrics(D, selected.final.w, patient, cfgSelected);
selectedIpoptMetrics = compute_solver_metrics( ...
    selected.final.resultGUI, struct(), selected.final.optimizer);
selectedDosePass = quality_pass_detail(selectedDoseDetail, denseDoseDetail, ...
    cfg.evaluation.ctvD95TolerancePercent);
supportPreserved = ~any(abs(selected.final.w(~selected.supportFull)) > 1e-10);
layerReduced = selected.exactLayerStats.nExactActiveLayers < ...
    zero.exactLayerStats.nExactActiveLayers;
constraintPass = selected.optimizer.parts.maxConstraintViolation <= ...
    max(1e-4, zero.optimizer.parts.maxConstraintViolation + 1e-6);
passed = selectedAlpha > 0 && layerReduced && selected.objectiveDescentPass && ...
    constraintPass && supportPreserved && selected.supportEmbeddingPreserved && ...
    ~strcmp(selected.optimizer.status, 'line_search_failed');
benchmarkReady = passed && representativenessPass;

trajectory = trajectory_table(selected);
writetable(trajectory, fullfile(outputDir, 'selected_objective_trajectory.csv'));
writetable(layer_group_table(selected), fullfile(outputDir, ...
    'selected_layer_groups.csv'));
structureTable = build_structure_comparison( ...
    denseDoseDetail, baselineDoseDetail, selectedDoseDetail);
writetable(structureTable, fullfile(outputDir, ...
    'final_ipopt_structure_dose_comparison.csv'));
summary = build_summary(passed, representativenessPass, benchmarkReady, ...
    selectedDosePass, selectedAlpha, selectedLambda, zero, ...
    selected, denseDose, denseDelivery, baselineDose, baselineDelivery, selectedMetrics, ...
    selectedIpoptMetrics, supportPreserved, constraintPass);
writetable(struct2table(summary), fullfile(outputDir, 'reduced_layer_summary.csv'));
save_outputs(passed, selectedIx, zero, runs, recordTable, artifactFile, ...
    cfg, baselineDose, baselineDelivery, ipoptMetrics, outputDir, selected, ...
    selectedMetrics, summary, denseDose, denseDelivery, structureTable);
if ~passed
    error('run_integrated_layer_validation_20deg:selectedFailed', ...
        'Selected nonzero lambda did not pass the reduced layer validation gate.');
end
fprintf('\nREDUCED NUMERICAL LAYER VALIDATION PASSED.\n');
fprintf('FULL 20-DEGREE BENCHMARK READINESS: %s.\n', pass_fail(benchmarkReady));
outputs = struct('numericalValidationPassed', passed, ...
    'representativenessPassed', representativenessPass, ...
    'fullBenchmarkReady', benchmarkReady, 'outputDir', outputDir, ...
    'selectedAlpha', selectedAlpha, 'selectedLambdaEL', selectedLambda, ...
    'summary', summary);
end

function add_module_paths(root)
folders = {'config','planning','mapping','objective','delivery','reduction', ...
    'robustness','evaluation','integrated'};
for i = 1:numel(folders), addpath(fullfile(root, folders{i})); end
end

function D = nominal_matrix(dij)
if iscell(dij.physicalDose), D = dij.physicalDose{1}; else, D = dij.physicalDose; end
end

function metrics = summarize_plan(w, D, patient, map, groups, cfg, machine)
metrics.dose = dose_summary(D, w, patient, cfg);
metrics.delivery = compute_delivery_metrics(w, map, groups, cfg, machine);
end

function summary = dose_summary(D, w, patient, cfg)
 m = dose_metrics(D, w, patient, cfg);
summary = m.summary;
end

function m = dose_metrics(D, w, patient, cfg)
m = compute_dvh_metrics(full(D * reshape(double(w), [], 1)), ...
    patient.ct, patient.cst, cfg);
end

function r = empty_record()
r = struct('alpha', NaN, 'lambdaEL', NaN, 'objectiveInitial', NaN, ...
    'objectiveFinal', NaN, 'doseObjectiveFinal', NaN, ...
    'activeLayers', NaN, 'activeSpots', NaN, ...
    'exactActiveLayers', NaN, 'exactZeroLayers', NaN, ...
    'exactLayerReduction', NaN, 'layerReduction', NaN, ...
    'objectiveDescentPass', false, 'supportEmbeddingPreserved', false, ...
    'targetD95', NaN, 'targetD98', NaN, 'oarDmax', NaN, ...
    'd95ChangePercent', NaN, 'd98ChangePercent', NaN, ...
    'oarChangePercent', NaN, 'doseQualityPass', false, ...
    'maxConstraintViolation', NaN, 'constraintPass', false, ...
    'estimatedBDT', NaN, 'iterations', NaN, 'status', 'pending', ...
    'errorIdentifier', '', 'errorMessage', '');
end

function r = failed_record(alpha, lambda, trialError)
r = empty_record();
r.alpha = alpha;
r.lambdaEL = lambda;
r.status = ['error:' trialError.identifier];
r.errorIdentifier = trialError.identifier;
r.errorMessage = trialError.message;
end

function r = make_record(alpha, lambda, trial, metrics, baseDose, baseExactLayers)
r = empty_record();
r.alpha = alpha; r.lambdaEL = lambda;
r.objectiveInitial = trial.initialObjective;
r.objectiveFinal = trial.optimizer.objective;
r.doseObjectiveFinal = trial.optimizer.parts.dose;
r.activeLayers = metrics.delivery.nActiveLayers;
r.activeSpots = metrics.delivery.nActiveSpots;
r.exactActiveLayers = trial.exactLayerStats.nExactActiveLayers;
r.exactZeroLayers = trial.exactLayerStats.nExactZeroLayers;
r.exactLayerReduction = baseExactLayers.nExactActiveLayers - ...
    trial.exactLayerStats.nExactActiveLayers;
r.layerReduction = r.exactLayerReduction;
r.objectiveDescentPass = trial.objectiveDescentPass;
r.supportEmbeddingPreserved = trial.supportEmbeddingPreserved;
r.targetD95 = metrics.dose.targetD95Min;
r.targetD98 = metrics.dose.targetD98Min;
r.oarDmax = metrics.dose.oarDmaxMax;
r.d95ChangePercent = percent_change(r.targetD95, baseDose.targetD95Min);
r.d98ChangePercent = percent_change(r.targetD98, baseDose.targetD98Min);
r.oarChangePercent = percent_change(r.oarDmax, baseDose.oarDmaxMax);
r.doseQualityPass = quality_pass(metrics.dose, baseDose, 2);
r.maxConstraintViolation = trial.optimizer.parts.maxConstraintViolation;
r.constraintPass = r.maxConstraintViolation <= 1e-4;
r.estimatedBDT = metrics.delivery.T_total;
r.iterations = trial.optimizer.iterations;
r.status = trial.optimizer.status;
end

function pass = quality_pass(candidate, baseline, tolerance)
pass = percent_change(candidate.targetD95Min, baseline.targetD95Min) >= -tolerance && ...
    percent_change(candidate.targetD98Min, baseline.targetD98Min) >= -tolerance && ...
    percent_change(candidate.oarDmaxMax, baseline.oarDmaxMax) <= tolerance;
end

function pass = quality_pass_detail(candidate, baseline, tolerance)
pass = true;
for i = 1:numel(candidate.structures)
    current = candidate.structures(i);
    reference = baseline.structures(i);
    if current.isTarget
        pass = pass && percent_change(current.D95, reference.D95) >= -tolerance && ...
            percent_change(current.D98, reference.D98) >= -tolerance;
    elseif strcmpi(current.type, 'OAR')
        pass = pass && percent_change(current.Dmean, reference.Dmean) <= tolerance && ...
            percent_change(current.Dmax, reference.Dmax) <= tolerance;
    end
end
end

function tbl = build_structure_comparison(dense, reduced, final)
n = numel(dense.structures);
rows = repmat(struct('structure', '', 'type', '', ...
    'denseD98', NaN, 'reducedD98', NaN, 'finalD98', NaN, ...
    'denseD95', NaN, 'reducedD95', NaN, 'finalD95', NaN, ...
    'denseDmean', NaN, 'reducedDmean', NaN, 'finalDmean', NaN, ...
    'denseDmax', NaN, 'reducedDmax', NaN, 'finalDmax', NaN, ...
    'finalD95ChangePercent', NaN, 'finalD98ChangePercent', NaN, ...
    'finalDmeanChangePercent', NaN, 'finalDmaxChangePercent', NaN), n, 1);
for i = 1:n
    d = dense.structures(i); r = reduced.structures(i); f = final.structures(i);
    rows(i).structure = d.name; rows(i).type = d.type;
    rows(i).denseD98 = d.D98; rows(i).reducedD98 = r.D98; rows(i).finalD98 = f.D98;
    rows(i).denseD95 = d.D95; rows(i).reducedD95 = r.D95; rows(i).finalD95 = f.D95;
    rows(i).denseDmean = d.Dmean; rows(i).reducedDmean = r.Dmean; rows(i).finalDmean = f.Dmean;
    rows(i).denseDmax = d.Dmax; rows(i).reducedDmax = r.Dmax; rows(i).finalDmax = f.Dmax;
    rows(i).finalD95ChangePercent = percent_change(f.D95, d.D95);
    rows(i).finalD98ChangePercent = percent_change(f.D98, d.D98);
    rows(i).finalDmeanChangePercent = percent_change(f.Dmean, d.Dmean);
    rows(i).finalDmaxChangePercent = percent_change(f.Dmax, d.Dmax);
end
tbl = struct2table(rows);
end

function tbl = build_zero_structure_comparison(dense, reduced, tolerance)
n = numel(dense.structures);
rows = repmat(struct('structure', '', 'type', '', 'isTarget', false, ...
    'denseD98', NaN, 'zeroD98', NaN, 'D98ChangePercent', NaN, ...
    'denseD95', NaN, 'zeroD95', NaN, 'D95ChangePercent', NaN, ...
    'denseDmean', NaN, 'zeroDmean', NaN, 'DmeanChangePercent', NaN, ...
    'denseDmax', NaN, 'zeroDmax', NaN, 'DmaxChangePercent', NaN, ...
    'structurePass', true), n, 1);
for i = 1:n
    d = dense.structures(i);
    r = reduced.structures(i);
    rows(i).structure = d.name;
    rows(i).type = d.type;
    rows(i).isTarget = d.isTarget;
    rows(i).denseD98 = d.D98; rows(i).zeroD98 = r.D98;
    rows(i).denseD95 = d.D95; rows(i).zeroD95 = r.D95;
    rows(i).denseDmean = d.Dmean; rows(i).zeroDmean = r.Dmean;
    rows(i).denseDmax = d.Dmax; rows(i).zeroDmax = r.Dmax;
    rows(i).D98ChangePercent = percent_change(r.D98, d.D98);
    rows(i).D95ChangePercent = percent_change(r.D95, d.D95);
    rows(i).DmeanChangePercent = percent_change(r.Dmean, d.Dmean);
    rows(i).DmaxChangePercent = percent_change(r.Dmax, d.Dmax);
    if d.isTarget
        rows(i).structurePass = rows(i).D95ChangePercent >= -tolerance && ...
            rows(i).D98ChangePercent >= -tolerance;
    elseif strcmpi(d.type, 'OAR')
        rows(i).structurePass = rows(i).DmeanChangePercent <= tolerance && ...
            rows(i).DmaxChangePercent <= tolerance;
    end
end
tbl = struct2table(rows);
end

function s = build_zero_summary(zero, denseDose, denseDelivery, baseDose, ...
    baseDelivery, ipoptMetrics, representativenessPass)
s = struct('representativenessPassed', representativenessPass, ...
    'doseEquivalenceRelativeError', zero.doseEquivalenceRelativeError, ...
    'gradientMaximumRelativeError', zero.gradient.maximumRelativeError, ...
    'objectiveDescentPass', zero.objectiveDescentPass, ...
    'supportEmbeddingPreserved', zero.supportEmbeddingPreserved, ...
    'maxConstraintViolation', zero.optimizer.parts.maxConstraintViolation, ...
    'denseLayers', denseDelivery.nActiveLayers, ...
    'zeroLayers', baseDelivery.nActiveLayers, ...
    'zeroExactActiveLayers', zero.exactLayerStats.nExactActiveLayers, ...
    'denseSpots', denseDelivery.nActiveSpots, ...
    'zeroSpots', baseDelivery.nActiveSpots, ...
    'denseD95', denseDose.targetD95Min, ...
    'zeroD95', baseDose.targetD95Min, ...
    'D95ChangePercent', percent_change(baseDose.targetD95Min, denseDose.targetD95Min), ...
    'denseD98', denseDose.targetD98Min, ...
    'zeroD98', baseDose.targetD98Min, ...
    'D98ChangePercent', percent_change(baseDose.targetD98Min, denseDose.targetD98Min), ...
    'denseOarDmax', denseDose.oarDmaxMax, ...
    'zeroOarDmax', baseDose.oarDmaxMax, ...
    'OarDmaxChangePercent', percent_change(baseDose.oarDmaxMax, denseDose.oarDmaxMax), ...
    'denseBDT', denseDelivery.T_total, 'zeroBDT', baseDelivery.T_total, ...
    'integratedStatus', zero.optimizer.status, ...
    'finalIpoptStatus', ipoptMetrics.statusMessage);
end

function tbl = trajectory_table(run)
n = numel(run.objectiveTrajectory);
iteration = (0:n-1)';
objective = run.objectiveTrajectory(:);
tbl = table(iteration, objective);
if n > 1
    h = run.optimizer.history;
    tbl.doseObjective = [run.initialParts.dose; h.doseObjective(:)];
    tbl.layerPenalty = [run.initialParts.layerL21half; h.layerPenalty(:)];
    tbl.maxConstraintViolation = [run.initialParts.maxConstraintViolation; ...
        h.maxConstraintViolation(:)];
    tbl.stepSize = [NaN; h.stepSize(:)];
end
end

function tbl = layer_group_table(run)
s = run.exactLayerStats;
groupIndex = s.groupIndex(:);
cpIndex = s.cpIndex(:);
energyIndex = s.energyIndex(:);
energy = s.energy(:);
groupNorm = s.groupNorm(:);
exactZero = s.exactZeroMask(:);
tbl = table(groupIndex, cpIndex, energyIndex, energy, groupNorm, ...
    exactZero);
end

function token = alpha_file_token(alpha)
token = strrep(sprintf('%.4g', alpha), '.', 'p');
token = strrep(token, '-', 'm');
end

function label = pass_fail(value)
if value
    label = 'PASS';
else
    label = 'FAIL';
end
end

function p = percent_change(value, baseline)
p = 100 * (double(value) - double(baseline)) / max(abs(double(baseline)), eps);
end

function s = build_summary(passed, representativenessPass, benchmarkReady, ...
    selectedDosePass, alpha, lambda, zero, selected, denseDose, ...
