function test_compute_delivery_metrics()
% test_compute_delivery_metrics  Focused validation for Task 31 helper.

fprintf('\n========================================\n');
fprintf('TEST: compute_delivery_metrics (Task 31)\n');
fprintf('========================================\n');

seq = repmat(struct( ...
    'cpIndex', 0, ...
    'gantryAngle', 0, ...
    'energy', 0, ...
    'energyIndex', 0, ...
    'spotIndices', [], ...
    'spotWeights', [], ...
    'numActiveSpots', 0, ...
    'layerWeightSum', 0, ...
    'prevEnergy', [], ...
    'nextEnergy', []), 3, 1);

seq(1) = struct('cpIndex', 1, 'gantryAngle', 0,  'energy', 150, 'energyIndex', 1, ...
    'spotIndices', [1; 2], 'spotWeights', [0.3; 0.1], 'numActiveSpots', 2, ...
    'layerWeightSum', 0.4, 'prevEnergy', [], 'nextEnergy', 140);
seq(2) = struct('cpIndex', 1, 'gantryAngle', 0,  'energy', 140, 'energyIndex', 2, ...
    'spotIndices', 3, 'spotWeights', 0.05, 'numActiveSpots', 1, ...
    'layerWeightSum', 0.05, 'prevEnergy', 150, 'nextEnergy', 145);
seq(3) = struct('cpIndex', 2, 'gantryAngle', 20, 'energy', 145, 'energyIndex', 1, ...
    'spotIndices', [4; 5], 'spotWeights', [0.2; 0.01], 'numActiveSpots', 2, ...
    'layerWeightSum', 0.21, 'prevEnergy', 140, 'nextEnergy', []);

machine = default_machine_model();
cfg = struct('mmuThreshold', 0.08);

metrics = compute_delivery_metrics(seq, machine, cfg);

assert(metrics.nControlPoints == 2);
assert(metrics.nActiveLayers == 3);
assert(metrics.nActiveSpots == 5);
assert(metrics.nSwitchUp == 1);
assert(abs(metrics.totalSwitchMagnitude - 15) < 1e-12);
assert(abs(metrics.spotWeightMin - 0.01) < 1e-12);
assert(abs(metrics.spotWeightMedian - 0.1) < 1e-12);
assert(metrics.nSubMMU == 2);
assert(abs(metrics.pctSubMMU - 40) < 1e-12);
assert(abs(metrics.T_total - (metrics.T_energy + metrics.T_spot + metrics.T_irradiation + metrics.T_gantry + metrics.T_buffer)) < 1e-12);

fprintf('[PASS] Delivery metrics computed consistently.\n');
end
